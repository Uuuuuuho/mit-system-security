#!/usr/bin/env python3
"""Generate defects.vh (the magic constants of psp-mini's two planted defects).

    gen_defects.py OUTDIR [SEED] [--keep]

With --keep, an existing OUTDIR/defects.vh is kept unless a different SEED is
given (this is what `make` does, so the defects stay put between runs; use
`make newseed` or `make SEED=n` to move them).

Writes OUTDIR/defects.vh (included by rtl/psp_mini.v) and OUTDIR/defects.json
(just the seed).  The Verilog constants are split into XOR pairs so that the
magic values are not readable at a glance.  The grader recomputes the plain
values with values(seed) to check that a counterexample really triggers the
defect.  (Yes, you could do the same -- but then you learn nothing.)

Defect #1 (PSP_GLITCH):   adder result ^= FLIP  when  a == GA and b[7:0] == GB
Defect #2 (PSP_BACKDOOR): custom-0 insn with funct3 == BF3, funct7 == BF7 and
                          x[rs1] == BKEY raises privilege to M (no trap).
"""
import json
import os
import random
import sys
import time


def values(seed):
    """The plain defect parameters for a seed (used by the grader)."""
    rng = random.Random(seed)
    ga = rng.getrandbits(32)
    while ga < 0x1000 or ga > 0xFFFFF000:   # never reachable by a single ADDI/LUI
        ga = rng.getrandbits(32)
    gb = rng.getrandbits(8)
    flip = 1 << rng.randrange(0, 32)
    bf3 = rng.getrandbits(3)
    bf7 = rng.getrandbits(7)
    bkey = rng.getrandbits(32)
    while bkey < 0x1000 or bkey > 0xFFFFF000:
        bkey = rng.getrandbits(32)
    return {"seed": seed, "glitch_a": ga, "glitch_b": gb, "glitch_flip": flip,
            "bd_funct3": bf3, "bd_funct7": bf7, "bd_key": bkey}


def main():
    args = [a for a in sys.argv[1:] if a != "--keep"]
    keep = "--keep" in sys.argv
    if not args:
        sys.exit(__doc__)
    outdir = args[0]
    want = args[1] if len(args) > 1 and args[1] != "" else None
    jpath = os.path.join(outdir, "defects.json")
    if keep and os.path.exists(jpath) and os.path.exists(os.path.join(outdir, "defects.vh")):
        try:
            old = json.load(open(jpath))["seed"]
        except (ValueError, KeyError, OSError):
            old = None
        if old is not None and (want is None or int(want) == old):
            return
    seed = int(want) if want is not None else \
        (int(time.time() * 1e6) ^ os.getpid()) & 0xFFFFFFFF
    d = values(seed)
    rng = random.Random(seed ^ 0x5A5A5A5A)

    def split(v, bits):
        m = rng.getrandbits(bits)
        return m, v ^ m

    g0, g1 = split(d["glitch_a"], 32)
    g2, g3 = split(d["glitch_b"], 8)
    flip = d["glitch_flip"]
    b0, b1 = split(d["bd_funct3"], 3)
    b2, b3 = split(d["bd_funct7"], 7)
    b4, b5 = split(d["bd_key"], 32)

    os.makedirs(outdir, exist_ok=True)
    vh = f"""// defects.vh -- GENERATED by tools/gen_defects.py; do not edit.
// Regenerate with a different SEED to move the defects around.
`ifndef PSP_DEFECTS_VH
`define PSP_DEFECTS_VH
`define PSP_G_K0 32'h{g0:08x}
`define PSP_G_K1 32'h{g1:08x}
`define PSP_G_K2 8'h{g2:02x}
`define PSP_G_K3 8'h{g3:02x}
`define PSP_G_K4 32'h{flip:08x}
`define PSP_B_K0 3'h{b0:x}
`define PSP_B_K1 3'h{b1:x}
`define PSP_B_K2 7'h{b2:02x}
`define PSP_B_K3 7'h{b3:02x}
`define PSP_B_K4 32'h{b4:08x}
`define PSP_B_K5 32'h{b5:08x}
`endif
"""
    with open(os.path.join(outdir, "defects.vh"), "w") as f:
        f.write(vh)
    with open(os.path.join(outdir, "defects.json"), "w") as f:
        json.dump({"seed": seed}, f)        # only the seed: no spoilers in build/
        f.write("\n")
    print(f"gen_defects: placed the defects with seed {seed} ({outdir}/defects.vh)")


if __name__ == "__main__":
    main()
